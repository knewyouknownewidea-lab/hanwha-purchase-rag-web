import assert from "node:assert/strict";
import test from "node:test";
import { loadSample } from "../src/data/sampleData";
import { createPriceSample } from "../src/data/priceSample";
import { runAnalysis } from "../src/lib/analysis";
import { resultSheets } from "../src/lib/exporters";
import { derive } from "../src/lib/metrics";
import { buildPriceAnalysis, priceAnalysisResult, updateExternalQuote } from "../src/lib/priceComparison";
import { buildXlsx, type XSheet } from "../src/lib/xlsx";

const cell = (sheet: XSheet, row: number, header: string) => sheet.rows[row][sheet.columns.findIndex((column) => column.header === header)];

test("price export keeps common identity, recalculated amounts, quote verdicts, documents and honest API state", () => {
  const { data, meta } = loadSample();
  const inputs = createPriceSample(data, meta);
  inputs.indicators[0] = { ...inputs.indicators[0], status: "connected", value: 1400, source: "환율 API", sourceUrl: "https://example.test/fx", observedAt: "2026-10-23", fetchedAt: "2026-10-26T01:00:00Z", message: "환율 참고 조회", isSample: false };
  inputs.indicators[1] = { ...inputs.indicators[1], status: "unavailable", value: 999, message: "조회 실패" };
  const changed = updateExternalQuote(inputs, "EXT-LINER-002", 1040000);
  const analysis = buildPriceAnalysis(data, meta, changed, { itemCode: "ITM-1001" });
  const result = priceAnalysisResult(analysis, derive(data, meta.asOf));
  const sheets = resultSheets(result, "가격 검토");
  assert.deepEqual(sheets.map((sheet) => sheet.name), ["결과 표", "조건·근거", "가격 견적·판정", "가격 문서 근거", "외부 API 참고"]);
  const [table, info, quotes, documents, api] = sheets;
  const infoValues = new Map(info.rows.map((row) => [row[0], row[1]]));
  assert.equal(infoValues.get("가격 분석 식별자"), analysis.id);
  assert.equal(infoValues.get("가격 분석 버전"), changed.revision);
  assert.equal(infoValues.get("가격 분석 데이터 ID"), meta.dataId);
  assert.equal(infoValues.get("가격 분석 데이터 버전"), meta.version);
  assert.equal(infoValues.get("시장 참고가격"), 1020000);
  assert.equal(infoValues.get("가격 비교 조건 · 검사 조건"), inputs.conditions.inspection);
  assert.equal(cell(table, 0, "외부 시장 참고가격"), 1020000);
  assert.equal(cell(table, 0, "차액"), 100000);
  assert.equal(cell(table, 3, "차액"), null);
  assert.equal(cell(table, 3, "차이율"), null);
  assert.equal(cell(quotes, 3, "비교 상태"), "비교 제외");
  assert.match(String(cell(quotes, 3, "제외·확인 사유")), /검사 조건 차이/);
  assert.equal(cell(quotes, 3, "견적 조건 · 검사 조건"), inputs.supplierQuotes[3].conditions.inspection);
  assert.equal(cell(quotes, 5, "견적·계약 ID"), "EXT-LINER-002");
  assert.equal(cell(quotes, 5, "단가"), 1040000);
  assert.equal(cell(quotes, 5, "중앙값 산정 사용"), "사용");
  assert.equal(cell(quotes, 5, "문서 식별자"), "PRICE-EXT-002");
  assert.equal(cell(quotes, 5, "문서일자"), "2026-10-15");
  assert.equal(cell(quotes, 5, "페이지"), "1");
  assert.equal(documents.rows.length, 7);
  assert.equal(cell(documents, 0, "적용 협력사 ID"), "SUP-001");
  assert.equal(cell(documents, 0, "연결 견적·계약 ID"), "INT-LINER-A");
  assert.match(String(cell(documents, 0, "문서에 기록된 내용")), /가격 차이의 원가 사유는 이 문서에 기재되어 있지 않다/);
  assert.equal(cell(api, 0, "조회 상태"), "실제 API 조회");
  assert.equal(cell(api, 0, "조회값"), 1400);
  assert.equal(cell(api, 0, "관측 기준일"), "2026-10-23");
  assert.equal(cell(api, 0, "조회 시각"), "2026-10-26T01:00:00Z");
  assert.equal(cell(api, 0, "단위"), "KRW/USD");
  assert.equal(cell(api, 0, "출처 링크"), "https://example.test/fx");
  assert.equal(cell(api, 1, "조회 상태"), "API 조회 실패");
  assert.equal(cell(api, 1, "조회값"), null, "a failed API cannot export a stale number as the current value");
  assert.equal(cell(api, 2, "조회 상태"), "API 미연결");
  const bytes = buildXlsx(sheets);
  assert.deepEqual([...bytes.slice(0, 4)], [0x50, 0x4b, 0x03, 0x04]);
});

test("non-price exports retain the existing two sheets and result evidence", () => {
  const { data, meta } = loadSample();
  const result = runAnalysis({ kind: "supplier_compare", supplierIds: ["SUP-001", "SUP-002"] }, data, derive(data, meta.asOf), meta, "업체 A와 업체 B를 비교해줘");
  const sheets = resultSheets(result, "기존 협력사 비교");
  assert.equal(result.priceAnalysis, undefined);
  assert.deepEqual(sheets.map((sheet) => sheet.name), ["결과 표", "조건·근거"]);
  assert.equal(sheets[0].rows.length, result.rows.length);
  assert.equal(sheets[0].columns.at(-1)?.header, "순위 제외 사유");
  assert.equal(cell(sheets[0], 0, "대상"), result.rows[0].label);
  assert.equal(cell(sheets[0], 0, "강점"), result.rows[0].strengths.join(" / "));
  assert.ok(sheets[1].rows.some((row) => row[0] === "결과 이름" && row[1] === "기존 협력사 비교"));
  assert.ok(sheets[1].rows.some((row) => row[0] === "평가 근거 1" && row[1] === result.basis[0]));
  assert.ok(!sheets[1].rows.some((row) => row[0] === "가격 분석 식별자"));
});
